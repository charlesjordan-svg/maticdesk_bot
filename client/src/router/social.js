/**
 * The social layer. D165, amended by D198. Built 2026-09-04.
 *
 * ---------------------------------------------------------------------------------------------
 * THIS IS A SAFETY REQUIREMENT, NOT POLISH, AND D198 IS WHY.
 *
 * On 2026-09-03 someone typed *"Hello how are you?"* into the running app and got a `renew_dhcp`
 * CONSENT CARD. Every gate behaved correctly — the proposal was valid, the card rendered what the
 * broker retained, the audit record was honest. It was still a defect, and D198 records the reason:
 * **D130 makes the consent card the thing a user reads before their machine changes, and every card
 * offered for something the user did not ask for teaches them the card is noise to click past.**
 *
 * `consent-surface.test.mjs` will still pass on the day the card has become furniture. That is what
 * makes this a safety requirement.
 *
 * ---------------------------------------------------------------------------------------------
 * DETERMINISTIC, AND NOT MODEL-AUTHORED (D165)
 *
 * Every string here is a template that ships in the client. Nothing is generated by a model, and
 * nothing is hub-authored — under H5 hub text is inert, attributed, and never spoken by the avatar
 * as its own words, and these ARE the avatar's own words. Same family as H3e: constrain what text
 * the model is allowed to influence.
 *
 * It also means the social layer works with the cloud unreachable and the hub down, which is the
 * situation D198 was actually observed in.
 *
 * ---------------------------------------------------------------------------------------------
 * THE CAPABILITY ANSWER IS GENERATED FROM THE CATALOG. THIS IS THE POINT OF THE WHOLE FILE.
 *
 * D165: *"Capability answers are generated from the catalog, because a warm bot that claims a
 * capability it lacks is worse than a curt one."*
 *
 * So `capabilityReply()` takes `broker.listCapabilities()` and renders a sentence from it. There is
 * no hand-written list of what the assistant can do, anywhere — **a hand-written list is a claim,
 * and a generated one is a fact.** Add a capability to `catalog.json` and this answer grows; remove
 * one and it shrinks. It cannot drift, because there is nothing to keep in sync.
 *
 * The tier labels come from the catalog too, for the same reason the consent card's wording does
 * (`_plainNote`): text describing what a user is agreeing to must not be written by the thing
 * asking for the agreement.
 *
 * They are read from `capability.tierInfo`, which `InProcessBroker` attaches from the catalog's
 * `tiers/*` — **not** from `broker.catalog`. Reaching through a Broker into its catalog would be
 * the layering violation `broker.d.ts` exists to prevent, and `listCapabilities()` already carries
 * everything this file needs.
 */

/**
 * Turn a list of capability titles into a spoken clause: "A, B, C and D".
 *
 * Spoken, not printed. The avatar SAYS these replies (`say()` in the renderer), so the capability
 * answer has to be a sentence rather than a bulleted list — a list read aloud is worse than prose,
 * and the transcript shows the same text.
 *
 * @param {string[]} items
 */
function andList(items) {
  if (items.length === 0) return "";
  if (items.length === 1) return items[0];
  // Catalog titles CONTAIN "and" — "Release and renew the DHCP lease", "Disable and re-enable a
  // network adapter". Joining those with a plain "and" produced
  //   "...the DHCP lease and disable and re-enable a network adapter"
  // which is three `and`s in a row and unreadable aloud. Semicolons separate the items when any
  // item has its own conjunction, so the sentence structure survives the data.
  const sep = items.some((i) => / and /.test(i)) ? "; " : ", ";
  return `${items.slice(0, -1).join(sep)}${sep === "; " ? ";" : ","} and ${items.at(-1)}`;
}

/**
 * Lowercase a catalog title for use mid-sentence, without mangling an acronym.
 *
 * "Flush the DNS resolver cache" must not become "flush the dns resolver cache". Only the first
 * word is lowered, and only when it is not itself all-caps.
 *
 * @param {string} title
 */
function midSentence(title) {
  const [first, ...rest] = String(title ?? "").split(" ");
  if (!first) return "";
  const lowered = first === first.toUpperCase() && first.length > 1 ? first : first.toLowerCase();
  return [lowered, ...rest].join(" ");
}

/**
 * What the assistant can actually do, generated from the catalog.
 *
 * **It says what it CANNOT do in the same breath, and that is deliberate.** A user who asks "what
 * can you do" and hears four things will assume the fifth is included. Naming the boundary once, in
 * the answer itself, is cheaper than a support conversation about why it did not install Office.
 *
 * @param {{ capabilities?: Array<{id:string,title?:string,tier?:string,tierInfo?:{label?:string}}> }} deps
 */
export function capabilityReply({ capabilities = [] } = {}) {
  if (capabilities.length === 0) {
    // Not a hypothetical: an unsigned or unreadable catalog leaves the broker with none, and
    // claiming abilities from a catalog that failed to load is exactly what this file prevents.
    return "I can't see my own list of actions at the moment, so I'd rather not promise anything. "
      + "Tell me what's wrong and I'll either find company guidance for it or pass it to IT.";
  }

  const titles = capabilities.map((c) => midSentence(c.title ?? c.id));
  const disruptive = capabilities.filter((c) => (c.tierInfo?.label ?? "").toLowerCase().includes("disruptive"));

  const parts = [
    `On this machine I can ${andList(titles)}.`,
    "I always show you exactly what I'm about to do and wait for you to approve it — nothing happens until you do.",
  ];
  if (disruptive.length) {
    // Named rather than summarised: "one of them you will notice" is the kind of sentence that
    // sounds reassuring and tells the user nothing.
    parts.push(`${disruptive.length === 1 ? "One of those" : "Some of those"} — ${andList(disruptive.map((c) => midSentence(c.title ?? c.id)))} — you'll notice happen, so I'll say so before asking.`);
  }
  parts.push(
    "Anything beyond that list I can't do myself. I can look for company guidance on it, or hand it to IT with what I've already checked.",
  );
  return parts.join(" ");
}

/**
 * The templates. Keyed by the subkind `classify()` returns.
 *
 * Each is a FUNCTION of the catalog rather than a constant, so that any of them could name a real
 * capability if it needed to. Only `capability` does today — the rest deliberately do not, because
 * a greeting that lists features is a sales pitch and the user asked how the day was going.
 *
 * @type {Record<string, (deps: any) => string>}
 */
const TEMPLATES = {
  greeting: () =>
    "Hello. I'm here to help with anything wrong on this machine — tell me what you're seeing and I'll take a look.",

  // "How are you" gets an answer rather than a deflection, and then hands the turn back. A bot that
  // will not answer a pleasantry reads as broken rather than as focused.
  howareyou: () =>
    "I'm running fine, thanks for asking. What's going on with your machine?",

  thanks: () =>
    "You're welcome. If anything else looks wrong, just say.",

  farewell: () =>
    "Right you are. I'll be here in the taskbar if something else comes up.",

  capability: (deps) => capabilityReply(deps),

  // OFF-TOPIC. Redirects without being arch about it, and without pretending the question was
  // unclear — the user knows the weather is not an IT problem, and saying "I did not understand"
  // to a question we understood perfectly is a small lie that makes the assistant seem stupid.
  offtopic: () =>
    "That's outside what I do, I'm afraid — I only look after this machine. Anything wrong with it, though, and I'm your first stop.",
};

/**
 * Render the reply for a social subkind.
 *
 * @param {string} subkind
 * @param {{ capabilities?: any[] }} [deps]
 * @returns {string|null} null when there is no template, so a caller must fall through rather
 *   than speak an empty string. `classify()` and this table are meant to agree; returning null
 *   rather than "" means a disagreement is visible instead of silent.
 */
export function socialReply(subkind, deps = {}) {
  const t = TEMPLATES[subkind];
  if (!t) return null;
  const s = t(deps).trim();
  return s.length ? s : null;
}

/** The subkinds that have templates. Exported so a test can assert classify() agrees with it. */
export const SOCIAL_SUBKINDS = Object.keys(TEMPLATES);
